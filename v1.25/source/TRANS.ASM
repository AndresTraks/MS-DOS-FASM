; SCP ASM's DM, "define message": the bytes of a DB with the high bit set on
; the last of them, which is where a string ends everywhere this program
; prints or compares one.
macro DM [value]
{
 common
	db	value
	load dm$last byte from $-1
	store byte dm$last or 80h at $-1
}

	ORG	100H
