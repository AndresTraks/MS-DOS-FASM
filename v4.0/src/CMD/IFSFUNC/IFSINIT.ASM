procedure   IDispatch								 ;AN000;
	POP	word [cs:retn1] ; remove long return				 ;AN000;
	POP	word [cs:retn1+2]        ;AN000;
	POP	word [cs:DMY] ; remove flags					 ;AN000;
	XCHG	AX,BX			; save bx/move index to index reg		 ;AN000;
	SHL	BL,1			; convert byte to word index			 ;AN000;
	XOR	BH,BH			; convert to word index 			 ;AN000;
	POP	word [cs:DMY] ; save fictitious AX				 ;AN000;
	PUSH	word [cs:DMY] ; restore spot on stack 			 ;AN000;
	PUSH	word [cs:retn1+2] ; restore long return				 ;AN000;
	PUSH	word [cs:retn1]        ;AN000;
	PUSH	word [cs:FOO_] ; place near address of far return		 ;AN000;
	PUSH	word [cs:IFSTable+BX] ; place destination routine			 ;AN000;
	XCHG	AX,BX			; restore BX					 ;AN000;
	MOV	AX,[cs:DMY] ; restore AX					 ;AN000;
	STI				; let Mani see Clock ticks			 ;AN000;
ShortReturn:										 ;AN000;
	return				; go to routine (dispatch for Aaron)		 ;AN000;
