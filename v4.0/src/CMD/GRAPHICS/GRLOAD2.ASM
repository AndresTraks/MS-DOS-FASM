		    MOV  AL,[BX+TAB_ENTRY.NB_INT] ;; Number of table entries (intens);AN000;
		    MOV  [BP+DI+DISPLAYMODE_STR.NUM_PATTERNS],AL ;;				;AN000;
		.ENDIF			     ;; 				;AN000;
	     .ENDIF			  ;;					;AN000;
	  .ENDIF			   ;;					;AN000;
       .ENDIF			       ;;					;AN000;
    .ENDIF			       ;;					;AN000;
 .ENDIF 			       ;;					;AN000;
  RET				       ;;					;AN000;
