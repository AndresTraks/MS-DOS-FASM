;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;					;AN000;
;;										;AN000;
;; Module Name: 								;AN000;
;;   TERMINATE_DISPLAYMODE							;AN000;
;;										;AN000;
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;					;AN000;
				       ;;					;AN000;
				       ;;					;AN000;
TERMINATE_DISPLAYMODE:            ;;					;AN000;
				       ;;					;AN000;
  MOV  AX,[STMTS_DONE]       ;;					;AN000;
 .IF <<[PTD_FOUND]> EQ YES>, AND	;; For the matched PTD			;AN000;
 .IF <bit AX NAND BOX>, AND	;;  issue "Invalid parm value"           ;AN000;
 .IF <<[PRT_BOX_ERROR]> EQ NO> ;;  message if PRINTBOX ID not		;AN000;
				       ;;  matched in each DISPLAYMODE section	;AN000;
	 PUSH AX		       ;; Save STMT_DONE flags			;AN000;
	 MOV  AX,INVALID_PB	       ;;					;AN000;
	 MOV  CX,0		       ;;					;AN000;
	 CALL DISP_ERROR	       ;;					;AN000;
	 MOV  byte [BUILD_STATE],NO ;;					;AN000;
	 MOV  byte [PRT_BOX_ERROR],YES ;; Issue this message only once		;AN000;
	 POP  AX		       ;;					;AN000;
 .ENDIF 			       ;;					;AN000;
  AND  AX,GR			       ;; Check for missing statements is last	;AN000;
 .IF <AX NE GR> ;;  DISPLAYMODE section: 		;AN000;
     OR  byte [STMT_ERROR],MISSING ;;    GRAPHICS stmt is required		;AN000;
     MOV  byte [PARSE_ERROR],YES ;;					;AN000;
     MOV  byte [BUILD_STATE],NO ;;					;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
				       ;;					;AN000;
				       ;;					;AN000;
  RET				       ;;					;AN000;
				       ;;					;AN000;
;TERMINATE_DISPLAYMODE	ENDP	       ;;					;AN000;
				       ;;					;AN000;
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;					;AN000;
;;										;AN000;
;; Module Name: 								;AN000;
;;   TERMINATE_PRINTER								;AN000;
;;										;AN000;
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;					;AN000;
				       ;;					;AN000;
TERMINATE_PRINTER:            ;;					;AN000;
				       ;;					;AN000;
  MOV  AX,[BLOCK_END]       ;;					;AN000;
 .IF <AX A MAX_BLOCK_END>	;; Keep track of the largest PRINTER	;AN000;
    MOV  [MAX_BLOCK_END],AX      ;;  section so we can allow space for	;AN000;
 .ENDIF 			       ;;  reload with a different printer	;AN000;
				       ;;  type.				;AN000;
				       ;;					;AN000;
				       ;; Check for missing statements		;AN000;
  MOV  AX,[STMTS_DONE]       ;;					;AN000;
  AND  AX,DISP			       ;; At least one DISPLAYMODE		;AN000;
 .IF <AX NE DISP> ;;  must have been found in last 	;AN000;
     OR  byte [STMT_ERROR],MISSING ;;   PRINTER section			;AN000;
     MOV  byte [PARSE_ERROR],YES ;;					;AN000;
     MOV  byte [BUILD_STATE],NO ;;					;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
  RET				       ;;					;AN000;
				       ;;					;AN000;
;TERMINATE_PRINTER	ENDP	       ;;					;AN000;
				       ;;					;AN000;
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;					;AN000;
;;										;AN000;
;; Module Name: 								;AN000;
;;   PARSE_PRINTER								;AN000;
;;										;AN000;
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;					;AN000;
				       ;;					;AN000;
label PRINTER_PARSE_PARMS word         ;; Parser control blocks 		;AN000;
	    DW	 PRINTER_P	       ;;					;AN000;
	    DB	 2		       ;; # of lists				;AN000;
	    DB	 0		       ;; # items in delimeter list		;AN000;
	    DB	 1		       ;; # items in end-of-line list		;AN000;
	    DB	 ';'                   ;; ';' used for comments                 ;AN000;
				       ;;					;AN000;
PRINTER_P   DB	 0,1		       ;; Required, max parms			;AN000;
	    DW	 PRINTER_P1	       ;;					;AN000;
	    DB	 0		       ;; # Switches				;AN000;
	    DB	 0		       ;; # keywords				;AN000;
				       ;;					;AN000;
PRINTER_P1  DW	 2000H		       ;; simple string 			;AN000;
	    DW	 0002H		       ;; Capitalize using character table	;AN000;
	    DW	 RESULT_BUFFER_grload2	       ;; Result buffer 			;AN000;
	    DW	 PRINTER_P1V	       ;; Value list				;AN000;
	    DB	 0		       ;; Synomyms				;AN000;
				       ;;					;AN000;
PRINTER_P1V    DB   3		       ;; # of value lists			;AN000;
	    DB	 0		       ;; # of range numerics			;AN000;
	    DB	 0		       ;; # of discrete numerics		;AN000;
	    DB	 1		       ;; # of strings				;AN000;
	    DB	 1		       ;; tag: index into verb jump table	;AN000;
PRINTER_P1V1  rw      1      ;; string offset 			;AN000;
				       ;;					;AN000;
				       ;;					;AN000;
CUR_PRINTER_TYPE   DB  0	       ;; Type of printer currently being	;AN000;
				       ;;  parsed:  1-color 2-b&w		;AN000;
				       ;;					;AN000;
PARSE_PRINTER:              ;;					;AN000;
				       ;;					;AN000;
  MOV  word [CUR_STMT],PRT  ;;					;AN000;
  MOV  byte [CUR_PRINTER_TYPE],BLACK_WHITE ;; Assume black & white until we hit	;AN000;
				       ;;  a COLORPRINT 			;AN000;
				       ;;					;AN000;
 .IF <bit <[STMTS_DONE]> AND PRT>	;; If not the first PRINTER section	;AN000;
     CALL  TERMINATE_DISPLAYMODE       ;;  then clean up the last one and	;AN000;
     CALL  TERMINATE_PRINTER	       ;;    the last DISPLAYMODE section.	;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
 MOV  AX,[FIRST_BLOCK]       ;;					;AN000;
 MOV  [BLOCK_START],AX       ;; Reset block pointers to start 	;AN000;
 MOV  [BLOCK_END],AX       ;;  of variable area			;AN000;
				       ;;					;AN000;
  MOV  word [STMTS_DONE],PRT  ;; Clear all bits except for PRT 	;AN000;
  MOV  word [GROUPS_DONE],0  ;; Clear 				;AN000;
				       ;;					;AN000;
 .IF <<[PTD_FOUND]> EQ YES> ;; PRINTER statement marks the end of	;AN000;
     MOV  byte [PTD_FOUND],PROCESSED ;;  the previous PTD			;AN000;
     MOV  byte [BUILD_STATE],NO ;; Stop building shared data		;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
  MOV  CL,[TAB_DIR_NB_ENTRIES]      ;; Reset the pattern table copy		;AN000;
  XOR  CH,CH			       ;;  pointers.  These pointers		;AN000;
  MOV  BX,TAB_DIRECTORY               ;;   are established when a pattern	;AN000;
 .REPEAT			       ;;    table is copied to the shared	;AN000;
    MOV [BX+TAB_ENTRY.TAB_COPY],-1 ;;     data area.  Initially they	;AN000;
; MASM worked LENGTH out as the number of elements a variable was
; declared with and SIZE as the bytes they take up.  The arrays these
; ask about are all of bytes, so the two come to the same number.
    ADD BX,sizeof.TAB_ENTRY      ;;      are -1.				;AN000;
 .LOOP				       ;;					;AN000;
				       ;;					;AN000;
  MOV  AX,PRINTER_TYPE_PARM            ;; Store printer type from command	;AN000;
  MOV  [PRINTER_P1V1],AX       ;;  line in value list			;AN000;
  MOV  DI,PRINTER_PARSE_PARMS          ;; parse parms				;AN000;
				       ;; SI => the line to parse		;AN000;
  XOR  DX,DX			       ;;					;AN000;
				       ;;					;AN000;
 .REPEAT			       ;;					;AN000;
     XOR  CX,CX 		       ;; Don't worry about number of operands  ;AN000;
     CALL SysParse		       ;;					;AN000;
    .IF <AX EQ 9> ;; Syntax error is the only thing	;AN000;
	OR  byte [STMT_ERROR],INVALID ;;  which can go wrong			;AN000;
	MOV  byte [PARSE_ERROR],YES ;;					;AN000;
	MOV  byte [BUILD_STATE],NO ;;					;AN000;
    .ENDIF			       ;;					;AN000;
 .UNTIL <AX EQ 0>, OR	;;					;AN000;
 .UNTIL <AX EQ -1> ;;					;AN000;
				       ;; Printer type parm matched one coded	;AN000;
				       ;;  on the PRINTER statement		;AN000;
 .IF <AX EQ 0> ;;					;AN000;
    .IF <<[PTD_FOUND]> EQ NO> ;;					;AN000;
	MOV  byte [PTD_FOUND],YES ;; If the printer type matches and	;AN000;
       .IF <<[PARSE_ERROR]> EQ NO>, AND	;;  no errors have been found yet	;AN000;
       .IF <<[PRT_BOX_ERROR]> EQ NO>, AND	;;					;AN000;
       .IF <<[MEM_OVERFLOW]> EQ NO> ;;					;AN000;
	   MOV byte [BUILD_STATE],YES ;;   then start building the shared	;AN000;
       .ENDIF			       ;;    data				;AN000;
    .ENDIF			       ;;					;AN000;
 .ELSE				       ;; No match				;AN000;
    MOV  byte [BUILD_STATE],NO  ;;					;AN000;
   .IF <AX NE -1> ;; Error during parse			;AN000;
      OR  byte [STMT_ERROR],INVALID ;; set error flag for caller		;AN000;
      MOV byte [PARSE_ERROR],YES ;; set error flag for caller		;AN000;
   .ENDIF			       ;;					;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
  RET										;AN000;
				       ;;					;AN000;
;PARSE_PRINTER  ENDP								;AN000;
										;AN000;
				       ;;					;AN000;
				       ;;					;AN000;
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;					;AN000;
;;										;AN000;
;; Module Name: 								;AN000;
;;   PARSE_DISPLAYMODE								;AN000;
;;										;AN000;
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;					;AN000;
				       ;;					;AN000;
label DISPMODE_PARSE_PARMS word        ;; Parser control blocks 		;AN000;
	    DW	 DISPMODE_P	       ;;					;AN000;
	    DB	 2		       ;; # of lists				;AN000;
	    DB	 0		       ;; # items in delimeter list		;AN000;
	    DB	 1		       ;; # items in end-of-line list		;AN000;
	    DB	 ';'                   ;; ';' used for comments                 ;AN000;
				       ;;					;AN000;
DISPMODE_P   DB   0,1		       ;; Required, max parms			;AN000;
	    DW	 DISPMODE_P1	       ;;					;AN000;
	    DB	 0		       ;; # Switches				;AN000;
	    DB	 0		       ;; # keywords				;AN000;
				       ;;					;AN000;
DISPMODE_P1  DW   8000H 	       ;; Numeric				;AN000;
	    DW	 0		       ;; No Capitalize 			;AN000;
	    DW	 RESULT_BUFFER_grload2	       ;; Result buffer 			;AN000;
	    DW	 DISPMODE_P1V	       ;; Value list				;AN000;
	    DB	 0		       ;; Synomyms				;AN000;
				       ;;					;AN000;
DISPMODE_P1V	DB   1			;; # of value lists			;AN000;
	    DB	 1		       ;; # of range numerics			;AN000;
	    DB	 1		       ;; tag					;AN000;
	    DD	 0,19		       ;; range 0..19				;AN000;
				       ;;					;AN000;
				       ;;					;AN000;
				       ;;					;AN000;
PARSE_DISPLAYMODE:              ;;					;AN000;
				       ;;					;AN000;
  MOV  word [CUR_STMT],DISP  ;;					;AN000;
				       ;; Check for a preceeding PRINTER	;AN000;
 .IF <bit <[STMTS_DONE]> NAND PRT>	;;					;AN000;
     OR  byte [STMT_ERROR],MISSING ;;					;AN000;
	MOV  byte [PARSE_ERROR],YES ;;					;AN000;
	MOV  byte [BUILD_STATE],NO ;;					;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
				       ;;					;AN000;
 .IF <bit <[STMTS_DONE]> NAND DISP>	;; If first DISPLAYMODE...		;AN000;
     .IF <<[BUILD_STATE]> EQ YES> ;;					;AN000;
	 MOV  AX,[BLOCK_END]      ;;					;AN000;
	 MOV  [BP+SHARED_DATA_AREA_STR.DISPLAYMODE_PTR],AX ;; Set pointer to first DISPLAYMODE	;AN000;
	 MOV  [BLOCK_START],AX      ;; New block starts after last one	;AN000;
     .ENDIF			       ;;					;AN000;
 .ELSE				       ;;					;AN000;
     CALL TERMINATE_DISPLAYMODE        ;; If not the first DISPLAYMODE then	;AN000;
				       ;;  clean up the last one.		;AN000;
     MOV  DI,[BLOCK_START]      ;; DI=pointer to DISPLAYMODE block just	;AN000;
     MOV  AX,[BLOCK_END]       ;;  built				;AN000;
    .IF <<[BUILD_STATE]> EQ YES> ;;					;AN000;
	MOV  [BP+DI+DISPLAYMODE_STR.NEXT_DISP_MODE],AX ;; Add new block to DISPLAYMODE chain	;AN000;
    .ENDIF			       ;;					;AN000;
     MOV  [BLOCK_START],AX      ;; New block starts after last one	;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
  MOV  AX,sizeof.DISPLAYMODE_STR      ;; Allocate space for new DISPLAYMODE	;AN000;
  CALL	GROW_SHARED_DATA	       ;;  block				;AN000;
 .IF <<[BUILD_STATE]> EQ YES> ;;					;AN000;
     MOV  DI,[BLOCK_START]      ;; Start of new block			;AN000;
     MOV  [BP+DI+DISPLAYMODE_STR.NUM_SETUP_ESC],0 ;; SETUP, RESTORE are optional so set ;AN000;
     MOV  [BP+DI+DISPLAYMODE_STR.NUM_RESTORE_ESC],0 ;;  to defaults			;AN000;
     MOV  [BP+DI+DISPLAYMODE_STR.SETUP_ESC_PTR],-1 ;;					;AN000;
     MOV  [BP+DI+DISPLAYMODE_STR.RESTORE_ESC_PTR],-1 ;;					;AN000;
     MOV  [BP+DI+DISPLAYMODE_STR.BOX_WIDTH],0 ;;					;AN000;
     MOV  [BP+DI+DISPLAYMODE_STR.BOX_HEIGHT],0 ;;					;AN000;
     MOV  [BP+DI+DISPLAYMODE_STR.PRINT_OPTIONS],0 ;; Default to NO print options	;AN000;
     MOV  [BP+DI+DISPLAYMODE_STR.NUM_DISP_MODE],0 ;; Get ready to INC this sucker		;AN000;
     MOV  [BP+DI+DISPLAYMODE_STR.NEXT_DISP_MODE],-1 ;; This is the last DISPLAYMODE for now! ;AN000;
     MOV  AX,[BLOCK_END]       ;;					;AN000;
     MOV  [BP+DI+DISPLAYMODE_STR.DISP_MODE_LIST_PTR],AX ;; Start mode list at end of new block	;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
  OR   word [STMTS_DONE],DISP  ;; Indicate DISPLAYMODE found		;AN000;
  AND  word [STMTS_DONE],NOT (BOX+GR+SET+REST) ;; Reset flags for PRINTBOX, GRAPHICS	;AN000;
				       ;;  stmts found				;AN000;
  AND  word [GROUPS_DONE],NOT (GR+SET+REST) ;; Reset flags for GRAPHICS, SETUP,	;AN000;
				       ;;  RESTORE groups processed		;AN000;
  MOV  DI,DISPMODE_PARSE_PARMS         ;; parse parms				;AN000;
				       ;; SI => the line to parse		;AN000;
  XOR  DX,DX			       ;;					;AN000;
 .REPEAT			       ;;					;AN000;
    XOR  CX,CX			       ;;					;AN000;
    CALL SysParse		       ;;					;AN000;
   .IF <AX EQ 0> ;; If mode is valid			;AN000;
	  PUSH AX		       ;;					;AN000;
	  MOV	AX,1		       ;; Add a mode to the list		;AN000;
	  CALL	GROW_SHARED_DATA       ;; Update block end			;AN000;
	 .IF <<[BUILD_STATE]> EQ YES> ;;					;AN000;
	     PUSH DI		       ;;					;AN000;
	     MOV  DI,[BLOCK_START]     ;;					;AN000;
	     INC  [BP+DI+DISPLAYMODE_STR.NUM_DISP_MODE] ;; Bump number of modes in list	;AN000;
	     MOV  DI,[BLOCK_END]      ;;					;AN000;
	     MOV  AL,[RESULT_VAL_grload2] ;; Get mode from result buffer		;AN000;
	     MOV  [BP+DI-1],AL	       ;; Store the mode at end of list 	;AN000;
	     POP  DI		       ;;					;AN000;
	 .ENDIF 		       ;;					;AN000;
	  POP  AX		       ;;					;AN000;
   .ELSE			       ;;					;AN000;
      .IF <AX NE -1> ;;					;AN000;
	  OR   byte [STMT_ERROR],INVALID ;; Mode is invalid			;AN000;
	  MOV  byte [PARSE_ERROR],YES ;;					;AN000;
	  MOV  byte [BUILD_STATE],NO ;;					;AN000;
      .ENDIF				  ;;					;AN000;
   .ENDIF			       ;;					;AN000;
 .UNTIL <AX EQ -1> ;;					;AN000;
				       ;;					;AN000;
  RET										;AN000;
				       ;;					;AN000;
;PARSE_DISPLAYMODE  ENDP 							;AN000;
										;AN000;
