				       ;;					;AN000;
label SETUP_PARSE_PARMS word       ;; Parser control blocks			;AN000;
	    DW	 SETUP_P	     ;; 					;AN000;
	    DB	 2		       ;; # of lists				;AN000;
	    DB	 0		       ;; # items in delimeter list		;AN000;
	    DB	 1		       ;; # items in end-of-line list		;AN000;
	    DB	 ';'                   ;; ';' used for comments                 ;AN000;
				       ;;					;AN000;
SETUP_P   DB   0,1		    ;; Required, max parms			;AN000;
	    DW	 SETUP_P1	    ;;						;AN000;
	    DB	 0		       ;; # Switches				;AN000;
	    DB	 0		       ;; # keywords				;AN000;
				       ;;					;AN000;
SETUP_P1 DW   08000H		    ;; Numeric					;AN000;
	    DW	 0		       ;; nO Capitalize 			;AN000;
	    DW	 RESULT_BUFFER_grload2	    ;; Result buffer				;AN000;
	    DW	 SETUP_P1V	    ;; Value list				;AN000;
	    DB	 0		       ;; Synomyms				;AN000;
				       ;;					;AN000;
				       ;;					;AN000;
SETUP_P1V    DB   1		    ;; # of value lists 			;AN000;
	    DB	 1		       ;; # of range numerics			;AN000;
	    DB	 1		       ;; tag					;AN000;
	    DD	 0,255		       ;; range 0..255				;AN000;
				       ;;					;AN000;
				       ;;					;AN000;
PARSE_SETUP:              ;;					;AN000;
				       ;;					;AN000;
  MOV  word [CUR_STMT],SET  ;;					;AN000;
 .IF <bit <[STMTS_DONE]> NAND DISP>	;; DISPLAYMODE must preceed this 	;AN000;
     OR  byte [STMT_ERROR],MISSING ;;					;AN000;
	MOV  byte [PARSE_ERROR],YES ;;					;AN000;
	MOV  byte [BUILD_STATE],NO ;;					;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
 .IF <bit <[GROUPS_DONE]> AND SET>	;; Check for previous group of SETUP	;AN000;
     OR  byte [STMT_ERROR],SEQUENCE ;;  stmts				;AN000;
	MOV  byte [PARSE_ERROR],YES ;;					;AN000;
	MOV  byte [BUILD_STATE],NO ;;					;AN000;
