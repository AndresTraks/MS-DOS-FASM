;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;					;AN000;
;;										;AN000;
;; Module Name: 								;AN000;
;;   PARSE_GRAPHICS								;AN000;
;;										;AN000;
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;					;AN000;
				       ;;					;AN000;
label GRAPHICS_PARSE_PARMS word        ;; Parser control blocks 		;AN000;
	    DW	 GRAPHICS_P	       ;;					;AN000;
	    DB	 2		       ;; # of lists				;AN000;
	    DB	 0		       ;; # items in delimeter list		;AN000;
	    DB	 1		       ;; # items in end-of-line list		;AN000;
	    DB	 ';'                   ;; ';' used for comments                 ;AN000;
				       ;;					;AN000;
GRAPHICS_P   DB   0,1		       ;; Required, max parms			;AN000;
	    DW	 GRAPHICS_P1	       ;;					;AN000;
	    DB	 0		       ;; # Switches				;AN000;
	    DB	 0		       ;; # keywords				;AN000;
				       ;;					;AN000;
GRAPHICS_P1 DW	 0A000H 	       ;; Numeric OR string			;AN000;
	    DW	 2		       ;; Capitalize				;AN000;
	    DW	 RESULT_BUFFER_grload3	       ;; Result buffer 			;AN000;
	    DW	 GRAPHICS_P1V	       ;; Value list				;AN000;
	    DB	 0		       ;; Synomyms				;AN000;
				       ;;					;AN000;
				       ;;					;AN000;
GRAPHICS_P1V	DB   3		       ;; # of value lists			;AN000;
	    DB	 1		       ;; # of range numerics			;AN000;
	    DB	 1		       ;; tag					;AN000;
	    DD	 0,255		       ;; range 0..255				;AN000;
	    DB	 0		       ;; 0 - no actual numerics		;AN000;
	    DB	 2		       ;; 2 STRING VALUES			;AN000;
	    DB	 2		       ;; tag					;AN000;
	    DW	 lowcount_str	       ;; ptr					;AN000;
	    DB	 3		       ;; tag					;AN000;
	    DW	 HIGHcount_str	       ;; ptr					;AN000;
				       ;;					;AN000;
lowcount_str  db  'LOWCOUNT',0         ;;                                       ;AN000;
HIGHcount_str  db  'HIGHCOUNT',0       ;;                                       ;AN000;
				       ;;					;AN000;
				       ;;					;AN000;
LOWCOUNT_FOUND	 DB  NO 	       ;;					;AN000;
HIGHCOUNT_FOUND  DB  NO 	       ;;					;AN000;
				       ;;					;AN000;
				       ;;					;AN000;
PARSE_GRAPHICS:             ;;					;AN000;
				       ;;					;AN000;
  MOV  word [CUR_STMT],GR  ;;					;AN000;
 .IF <bit <[STMTS_DONE]> NAND DISP>	;;					;AN000;
     OR  byte [STMT_ERROR],MISSING ;;					;AN000;
	MOV  byte [PARSE_ERROR],YES ;;					;AN000;
	MOV  byte [BUILD_STATE],NO ;;					;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
 .IF <<[BUILD_STATE]> EQ YES> ;;					;AN000;
     MOV  DI,[BLOCK_START]      ;;					;AN000;
     MOV  AX,[BLOCK_END]       ;;					;AN000;
     MOV  [BP+DI+DISPLAYMODE_STR.GRAPHICS_ESC_PTR],AX ;; Set pointer to GRAPHICS seq		;AN000;
     MOV  [BP+DI+DISPLAYMODE_STR.NUM_GRAPHICS_ESC],0 ;; Init sequence size			;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
  MOV  byte [LOWCOUNT_FOUND],NO ;; Flags to indicate whether the LOW	;AN000;
  MOV  byte [HIGHCOUNT_FOUND],NO ;;  and HIGHCOUNT parms were found	;AN000;
				       ;;					;AN000;
  OR   word [STMTS_DONE],GR  ;; Indicate GRAPHICS found		;AN000;
				       ;;					;AN000;
  MOV  AX,[PREV_STMT]       ;; Terminate any preceeding groups	;AN000;
  OR   [GROUPS_DONE],AX       ;;					;AN000;
				       ;;					;AN000;
  MOV  DI,GRAPHICS_PARSE_PARMS         ;; parse parms				;AN000;
				       ;; SI => the line to parse		;AN000;
  XOR  DX,DX			       ;;					;AN000;
 .REPEAT			       ;;					;AN000;
    XOR  CX,CX			       ;;					;AN000;
    CALL SysParse		       ;;					;AN000;
				       ;;					;AN000;
   .IF <AX EQ 0>, NEAR	;; If PARM is valid			;AN000;
	MOV  BL,[RESULT_TAG_grload3]      ;;					;AN000;
       .SELECT			       ;;					;AN000;
       .WHEN <BL EQ 1> ;; Escape byte				;AN000;
	  PUSH AX		       ;;					;AN000;
	  MOV	AX,1		       ;; Add a byte to the sequence		;AN000;
	  CALL	GROW_SHARED_DATA       ;; Update block end			;AN000;
	 .IF <<[BUILD_STATE]> EQ YES> ;;					;AN000;
	     PUSH DI		       ;;					;AN000;
	     MOV  DI,[BLOCK_START]     ;;					;AN000;
	     INC  [BP+DI+DISPLAYMODE_STR.NUM_GRAPHICS_ESC] ;; Bump number of bytes in sequence	;AN000;
	     MOV  DI,[BLOCK_END]      ;;					;AN000;
	     MOV  AL,[RESULT_VAL_grload3]      ;; Get esc byte from result buffer	;AN000;
	     MOV  [BP+DI-1],AL	       ;; Store at end of sequence		;AN000;
	     POP  DI		       ;;					;AN000;
	 .ENDIF 		       ;;					;AN000;
	  POP  AX		       ;;					;AN000;
       .WHEN <BL EQ 2> ;; LOWCOUNT				;AN000;
	  .IF <<[LOWCOUNT_FOUND]> EQ NO> ;;					;AN000;
	       MOV   byte [LOWCOUNT_FOUND],YES ;;					;AN000;
	       PUSH AX		       ;;					;AN000;
	       MOV   AX,1	       ;; Add a byte to the sequence		;AN000;
	       CALL  GROW_SHARED_DATA  ;; Update block end			;AN000;
	      .IF <<[BUILD_STATE]> EQ YES> ;;					;AN000;
		  PUSH DI	       ;;					;AN000;
		  MOV  DI,[BLOCK_START] ;;					;AN000;
		  INC  [BP+DI+DISPLAYMODE_STR.NUM_GRAPHICS_ESC] ;; Bump number of bytes in seq. ;AN000;
		  MOV  AX,[BLOCK_END]  ;; Save pointer to low byte		;AN000;
		  DEC  AX	       ;;					;AN000;
		  MOV  [BP+DI+DISPLAYMODE_STR.LOW_BYT_COUNT_PTR],AX ;AN000;
		  MOV  DI,AX	       ;;					;AN000;
		  MOV  byte [BP+DI],0    ;; Store 0 in place of count		;AN000;
		  POP  DI	       ;;					;AN000;
	      .ENDIF		       ;;					;AN000;
	       POP  AX		       ;;					;AN000;
				       ;;					;AN000;
	  .ELSE 		       ;;					;AN000;
	       OR  byte [STMT_ERROR],INVALID ;; Duplicate LOWCOUNT parms		;AN000;
	       MOV  byte [PARSE_ERROR],YES ;;					;AN000;
	       MOV  byte [BUILD_STATE],NO ;;					;AN000;
	  .ENDIF		       ;;					;AN000;
       .WHEN <BL EQ 3> ;; HIGHCOUNT				;AN000;
	  .IF <<[HIGHCOUNT_FOUND]> EQ NO> ;;					;AN000;
	      MOV   byte [HIGHCOUNT_FOUND],YES ;;					;AN000;
	      PUSH AX		       ;;					;AN000;
	      MOV   AX,1	       ;; Add a byte to the sequence		;AN000;
	      CALL  GROW_SHARED_DATA   ;; Update block end			;AN000;
	     .IF <<[BUILD_STATE]> EQ YES> ;;					;AN000;
		 PUSH DI	       ;;					;AN000;
		 MOV  DI,[BLOCK_START] ;;					;AN000;
		 INC  [BP+DI+DISPLAYMODE_STR.NUM_GRAPHICS_ESC] ;; Bump number of bytes in sequen;AN000;
		 MOV  AX,[BLOCK_END]   ;; Save pointer to high byte		;AN000;
		 DEC  AX	       ;; Block end always points 1 ahead	;AN000;
		 MOV  [BP+DI+DISPLAYMODE_STR.HGH_BYT_COUNT_PTR],AX ;AN000;
		 MOV  DI,AX	       ;;					;AN000;
		 MOV  byte [BP+DI],0    ;; Store 0 in place of count		;AN000;
		 POP  DI	       ;;					;AN000;
	     .ENDIF		       ;;					;AN000;
	      POP  AX		       ;;					;AN000;
	  .ELSE 		       ;;					;AN000;
	       OR  byte [STMT_ERROR],INVALID ;; Duplicate HIGHCOUNT parms		;AN000;
	       MOV  byte [PARSE_ERROR],YES ;;					;AN000;
	       MOV  byte [BUILD_STATE],NO ;;					;AN000;
	  .ENDIF		       ;;					;AN000;
       .ENDSELECT		       ;;					;AN000;
   .ELSE NEAR			       ;;					;AN000;
      .IF <AX NE -1> ;;					;AN000;
	  OR   byte [STMT_ERROR],INVALID ;; parm is invalid			;AN000;
	  MOV  byte [PARSE_ERROR],YES ;;					;AN000;
	  MOV  byte [BUILD_STATE],NO ;;					;AN000;
      .ENDIF			       ;;					;AN000;
   .ENDIF			       ;;					;AN000;
 .UNTIL <AX EQ -1>, NEAR	;;					;AN000;
				       ;;					;AN000;
 .IF <<[LOWCOUNT_FOUND]> EQ NO>, OR  ;;					;AN000;
 .IF <<[HIGHCOUNT_FOUND]> EQ NO>  ;; Missing LOWCOUNT/HIGHCOUNT parms	;AN000;
      OR   byte [STMT_ERROR],INVALID ;;					;AN000;
      MOV  byte [PARSE_ERROR],YES ;;					;AN000;
      MOV  byte [BUILD_STATE],NO ;;					;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
  RET				       ;;					;AN000;
				       ;;					;AN000;
;PARSE_GRAPHICS	ENDP		       ;;					;AN000;
				       ;;					;AN000;
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;					;AN000;
;;										;AN000;
;; Module Name: 								;AN000;
;;   PARSE_COLORSELECT								;AN000;
;;										;AN000;
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;					;AN000;
				       ;;					;AN000;
label COLORSELECT_PARSE_PARMS word     ;; Parser control blocks 		;AN000;
	    DW	 COLORSELECT_P	       ;;					;AN000;
	    DB	 2		       ;; # of lists				;AN000;
	    DB	 0		       ;; # items in delimeter list		;AN000;
	    DB	 1		       ;; # items in end-of-line list		;AN000;
	    DB	 ';'                   ;; ';' used for comments                 ;AN000;
				       ;;					;AN000;
				       ;;					;AN000;
label COLORSELECT_P byte           ;;					;AN000;
CS_NUM_REQ    DB   1,1		       ;; Required, max parms			;AN000;
label COLORSELECT_PARM word           ;;					;AN000;
CS_POSITIONAL rw      1      ;; Pointer to our positional		;AN000;
	      DB   0		       ;; # Switches				;AN000;
	      DB   0		       ;; # keywords				;AN000;
				       ;;					;AN000;
COLORSELECT_P0	DW   2000H	       ;; sTRING - display type 		;AN000;
	    DW	 2		       ;; Capitalize				;AN000;
	    DW	 RESULT_BUFFER_grload3	       ;; Result buffer 			;AN000;
	    DW	 COLORSELECT_P0V       ;; Value list				;AN000;
	    DB	 0		       ;; Synomyms				;AN000;
				       ;;					;AN000;
COLORSELECT_P0V    DB	0		   ;; # of value lists			;AN000;
;	    DB	 0		       ;; # of range numerics			;AN000;
;	    DB	 0		       ;; # of discrete numerics		;AN000;
;	    DB	 1		       ;; # of strings				;AN000;
;	    DB	 1		       ;; tag					;AN000;
;COLORSELECT_P0V1 DW   ?		   ;; string				;AN000;
				       ;;					;AN000;
COLORSELECT_P1	DW   8001H		  ;; Numeric - escape sequence byte	;AN000;
	    DW	 0		       ;; No Capitalize 			;AN000;
	    DW	 RESULT_BUFFER_grload3	       ;; Result buffer 			;AN000;
	    DW	 COLORSELECT_P1V	  ;; Value list 			;AN000;
	    DB	 0		       ;; Synomyms				;AN000;
				       ;;					;AN000;
COLORSELECT_P1V    DB	1		  ;; # of value lists			;AN000;
	    DB	 1		       ;; # of range numerics			;AN000;
	    DB	 1		       ;; tag					;AN000;
	    DD	 1,255		       ;; range 1..255				;AN000;
				       ;;					;AN000;
				       ;;					;AN000;
				       ;;					;AN000;
SEQ_LENGTH_PTR	DW   0		       ;; Number of colorselect statements	;AN000;
				       ;;					;AN000;
				       ;;					;AN000;
				       ;;					;AN000;
PARSE_COLORSELECT:              ;;					;AN000;
				      ;;					;AN000;
  MOV  word [CUR_STMT],COLS  ;;					;AN000;
 .IF <bit <[STMTS_DONE]> NAND PRT>	;; PRINTER  statemnet must have been	;AN000;
     OR  byte [STMT_ERROR],MISSING ;;  processed				;AN000;
	MOV  byte [PARSE_ERROR],YES ;;					;AN000;
	MOV  byte [BUILD_STATE],NO ;;					;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
 .IF <bit <[STMTS_DONE]> AND DISP+COLP>	;; DISDPLAYMODE and COLORPRINT  stmts	;AN000;
     OR  byte [STMT_ERROR],SEQUENCE ;;  should NOT have been processed	;AN000;
	MOV  byte [PARSE_ERROR],YES ;;					;AN000;
	MOV  byte [BUILD_STATE],NO ;;					;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
 .IF <bit <[GROUPS_DONE]> AND COLS>	;; Check for a previous group of 	;AN000;
     OR  byte [STMT_ERROR],SEQUENCE ;;  COLORSELECTS within this PTD 	;AN000;
	MOV  byte [PARSE_ERROR],YES ;;					;AN000;
	MOV  byte [BUILD_STATE],NO ;;					;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
 .IF <bit <[STMTS_DONE]> NAND COLS>	;; If first COLORSELECT...		;AN000;
      MOV  byte [NUM_BANDS],0  ;; Init number of COLORSELECT bands	;AN000;
     .IF <<[BUILD_STATE]> EQ YES> ;; Update count and pointer in the	;AN000;
	 MOV  AX,[BLOCK_END]      ;;  Shared Data Area header		;AN000;
	 MOV  [BP+SHARED_DATA_AREA_STR.COLORSELECT_PTR],AX ;; Set pointer to COLORSELECT info	;AN000;
	 MOV  [BP+SHARED_DATA_AREA_STR.NUM_PRT_BANDS],0 ;; Init NUMBER OF COLORSELECTS		;AN000;
     .ENDIF			       ;;					;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
  OR   word [STMTS_DONE],COLS  ;; Indicate found			;AN000;
 .IF <<[PREV_STMT]> NE COLS> ;; Terminate any preceeding groups	;AN000;
     MOV  AX,[PREV_STMT]       ;;  except for COLORSELECT		;AN000;
     OR   [GROUPS_DONE],AX      ;;					;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
  MOV	AX,1			       ;; Make room for sequence length field	;AN000;
  CALL	GROW_SHARED_DATA	       ;;					;AN000;
 .IF <<[BUILD_STATE]> EQ YES> ;;					;AN000;
     INC  [BP+SHARED_DATA_AREA_STR.NUM_PRT_BANDS] ;; Inc number of selects 		;AN000;
     MOV  DI,[BLOCK_END]       ;;					;AN000;
     MOV  byte [BP+DI-1],0            ;; Init sequence length field		;AN000;
     LEA  AX,[DI-1]		       ;;					;AN000;
     MOV  [SEQ_LENGTH_PTR],AX      ;; Save pointer to length of sequence	;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
  MOV  DI,COLORSELECT_PARSE_PARMS         ;; parse parms			;AN000;
  MOV  byte [CS_NUM_REQ],1  ;; Change to 1 required parameters	;AN000;
  MOV  AX,COLORSELECT_P0               ;; Point to control block for the band	;AN000;
  MOV  [CS_POSITIONAL],AX       ;;  ID.	(Dealing with only 1 positional ;AN000;
				       ;;  parameter at a time was the only way ;AN000;
				       ;;   I could get SYSPARSE to handle	;AN000;
				       ;;    the COLORSELECT syntax!)		;AN000;
				       ;; SI => the line to parse		;AN000;
  XOR  DX,DX			       ;;					;AN000;
  XOR  CX,CX			       ;;					;AN000;
				       ;;					;AN000;
  CALL SysParse 		       ;; PARSE the band ID			;AN000;
 .IF <AX NE 0> ;;					;AN000;
     OR  byte [STMT_ERROR],INVALID ;;					;AN000;
     MOV  byte [PARSE_ERROR],YES ;;					;AN000;
     MOV  byte [BUILD_STATE],NO ;;					;AN000;
     RET			       ;;  statement.				;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
  PUSH	ES			       ;; We got a band id........		;AN000;
  PUSH	DI			       ;;					;AN000;
				       ;;					;AN000;
  LES	DI,dword [RESULT_VAL_grload3]          ;; Get pointer to the parsed band id	;AN000;
 .IF <<byte [es:DI+1]> NE 0>     ;; Make sure the band id is only 	;AN000;
     OR  byte [STMT_ERROR],INVALID ;;  one byte long			;AN000;
     MOV  byte [PARSE_ERROR],YES ;;					;AN000;
     MOV  byte [BUILD_STATE],NO ;;					;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
  MOV  BL,[NUM_BANDS]       ;;					;AN000;
  XOR  BH,BH			       ;;					;AN000;
 .IF <BX EQ MAX_BANDS> ;; Watch out for too many COLORSELECTs	;AN000;
     OR  byte [STMT_ERROR],SEQUENCE ;;					;AN000;
     MOV  byte [PARSE_ERROR],YES ;;					;AN000;
     MOV  byte [BUILD_STATE],NO ;;					;AN000;
 .ELSE				       ;;					;AN000;
     SHL  BX,1			       ;; calc index to store band in value list;AN000;
     MOV  AL,[es:DI]		       ;; get BAND ID FROM PARSEr		;AN000;
     MOV  [BX+BAND_VAL_LIST],AL       ;;					;AN000;
     INC  byte [NUM_BANDS]  ;; bump number of bands			;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
  POP  DI			       ;;					;AN000;
  POP  ES			       ;;					;AN000;
				       ;;					;AN000;
				       ;;					;AN000;
  MOV  AX,COLORSELECT_P1               ;; Switch to numeric positional parm!!!	;AN000;
  MOV  [CS_POSITIONAL],AX       ;;					;AN000;
  MOV  byte [CS_NUM_REQ],0  ;; Change to 0 required parameters	;AN000;
  XOR  DX,DX			       ;; PARSE the sequence of escape bytes	;AN000;
 .REPEAT			       ;;					;AN000;
    XOR  CX,CX			       ;;					;AN000;
    CALL SysParse		       ;;					;AN000;
   .IF <AX EQ 0> ;; If esc byte is valid			;AN000;
	  PUSH AX		       ;;					;AN000;
	  MOV	AX,1		       ;; Add a byte to the sequence		;AN000;
	  CALL	GROW_SHARED_DATA       ;; Update block end			;AN000;
	 .IF <<[BUILD_STATE]> EQ YES> ;;					;AN000;
	     PUSH DI		       ;;					;AN000;
	     MOV  DI,[SEQ_LENGTH_PTR]  ;;					;AN000;
	     INC  byte [BP+DI]         ;; Bump number of bytes in sequence	;AN000;
	     MOV  DI,[BLOCK_END]      ;;					;AN000;
	     MOV  AL,[RESULT_VAL_grload3]      ;; Get esc byte from result buffer	;AN000;
	     MOV  [BP+DI-1],AL	       ;; Store at end of sequence		;AN000;
	     POP  DI		       ;;					;AN000;
	 .ENDIF 		       ;;					;AN000;
	  POP  AX		       ;;					;AN000;
   .ELSE			       ;;					;AN000;
      .IF <AX NE -1> ;;					;AN000;
	  OR   byte [STMT_ERROR],INVALID ;; parm is invalid			;AN000;
