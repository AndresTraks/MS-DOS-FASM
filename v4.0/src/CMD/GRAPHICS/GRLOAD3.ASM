PARSE_COLORPRINT:              ;;					;AN000;
				       ;;					;AN000;
  MOV  word [CUR_STMT],COLP  ;;					;AN000;
 .IF <bit <[STMTS_DONE]> NAND PRT>	;; PRINTER  statemnet must have been	;AN000;
     OR  byte [STMT_ERROR],MISSING ;;  processed				;AN000;
	MOV  byte [PARSE_ERROR],YES ;;					;AN000;
	MOV  byte [BUILD_STATE],NO ;;					;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
 .IF <bit <[STMTS_DONE]> AND DISP>	;; DISPLAYMODE stmts			;AN000;
     OR  byte [STMT_ERROR],SEQUENCE ;;  should NOT have been processed	;AN000;
	MOV  byte [PARSE_ERROR],YES ;;					;AN000;
	MOV  byte [BUILD_STATE],NO ;;					;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
 .IF <bit <[GROUPS_DONE]> AND COLP>	;; Check for a previous group of 	;AN000;
     OR  byte [STMT_ERROR],SEQUENCE ;;  COLORPRINTS within this PTD		;AN000;
	MOV  byte [PARSE_ERROR],YES ;;					;AN000;
	MOV  byte [BUILD_STATE],NO ;;					;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
  MOV  byte [CUR_PRINTER_TYPE],COLOR ;;					;AN000;
				       ;;					;AN000;
 .IF <bit <[STMTS_DONE]> NAND COLP>	;; If first COLORPRINT...		;AN000;
     .IF <<[BUILD_STATE]> EQ YES> ;; Update count and pointer in the	;AN000;
	 MOV  AX,[BLOCK_END]      ;;  Shared Data Area header		;AN000;
	 MOV  [BP+SHARED_DATA_AREA_STR.COLORPRINT_PTR],AX ;; Set pointer to COLORPRINT info	;AN000;
	 MOV  [BP+SHARED_DATA_AREA_STR.PRINTER_TYPE],COLOR ;;					;AN000;
	 MOV  [BP+SHARED_DATA_AREA_STR.NUM_PRT_COLOR],0 ;; Init NUMBER OF COLORPRINTS		;AN000;
     .ENDIF			       ;;					;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
 .IF <<[BUILD_STATE]> EQ YES> ;;					;AN000;
     INC  [BP+SHARED_DATA_AREA_STR.NUM_PRT_COLOR] ;; Inc number of selects 		;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
  OR   word [STMTS_DONE],COLP  ;; Indicate found			;AN000;
 .IF <<[PREV_STMT]> NE COLP> ;; Terminate any preceeding groups	;AN000;
     MOV  AX,[PREV_STMT]       ;;  except for COLORPRINT		;AN000;
     OR   [GROUPS_DONE],AX      ;;					;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
  MOV	AX,[BLOCK_END]       ;; Start a new block			;AN000;
  MOV	[BLOCK_START],AX       ;;					;AN000;
; MASM worked LENGTH out as the number of elements a variable was
; declared with and SIZE as the bytes they take up.  The arrays these
; ask about are all of bytes, so the two come to the same number.
  MOV	AX,sizeof.COLORPRINT_STR      ;; Make room for COLORPRINT info 	;AN000;
  CALL	GROW_SHARED_DATA	       ;;					;AN000;
				       ;;					;AN000;
  MOV  DI,COLORPRINT_PARSE_PARMS         ;; parse parms 			;AN000;
				       ;; SI => the line to parse		;AN000;
  XOR  DX,DX			       ;;					;AN000;
  XOR  CX,CX			       ;;					;AN000;
				       ;;					;AN000;
  CALL SysParse 		       ;; PARSE the RED value			;AN000;
 .IF <AX NE 0> ;;					;AN000;
     OR  byte [STMT_ERROR],INVALID ;;					;AN000;
     MOV  byte [PARSE_ERROR],YES ;;					;AN000;
     MOV  byte [BUILD_STATE],NO ;;					;AN000;
 .ELSE				       ;;					;AN000;
     .IF <<[BUILD_STATE]> EQ YES> ;;					;AN000;
	 PUSH  DI		       ;;					;AN000;
	 MOV  DI,[BLOCK_START]      ;;					;AN000;
	 MOV  AL,[RESULT_VAL_grload3]      ;; Store RED value in COLORPRINT info	;AN000;
	 MOV  [BP+DI+COLORPRINT_STR.RED],AL ;;					;AN000;
	 POP  DI		       ;;					;AN000;
     .ENDIF			       ;;					;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
  CALL SysParse 		       ;; PARSE the GREEN value 		;AN000;
 .IF <AX NE 0> ;;					;AN000;
     OR  byte [STMT_ERROR],INVALID ;;					;AN000;
     MOV  byte [PARSE_ERROR],YES ;;					;AN000;
     MOV  byte [BUILD_STATE],NO ;;					;AN000;
 .ELSE				       ;;					;AN000;
     .IF <<[BUILD_STATE]> EQ YES> ;;					;AN000;
	 PUSH  DI		       ;;					;AN000;
	 MOV  DI,[BLOCK_START]      ;;					;AN000;
	 MOV  AL,[RESULT_VAL_grload3]      ;; Store GREEN value in COLORPRINT info	;AN000;
	 MOV  [BP+DI+COLORPRINT_STR.GREEN],AL ;;					;AN000;
	 POP  DI		       ;;					;AN000;
     .ENDIF			       ;;					;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
  CALL SysParse 		       ;; PARSE the BLUE value			;AN000;
 .IF <AX NE 0> ;;					;AN000;
     OR  byte [STMT_ERROR],INVALID ;;					;AN000;
     MOV  byte [PARSE_ERROR],YES ;;					;AN000;
     MOV  byte [BUILD_STATE],NO ;;					;AN000;
 .ELSE				       ;;					;AN000;
     .IF <<[BUILD_STATE]> EQ YES> ;;					;AN000;
	 PUSH  DI		       ;;					;AN000;
	 MOV  DI,[BLOCK_START]      ;;					;AN000;
	 MOV  AL,[RESULT_VAL_grload3]      ;; Store BLUE value in COLORPRINT info	;AN000;
	 MOV  [BP+DI+COLORPRINT_STR.BLUE],AL ;;					;AN000;
	 POP  DI		       ;;					;AN000;
     .ENDIF			       ;;					;AN000;
 .ENDIF 			       ;;					;AN000;
				       ;;					;AN000;
 .IF <<[BUILD_STATE]> EQ YES> ;;					;AN000;
     PUSH  DI			       ;;					;AN000;
     MOV   DI,[BLOCK_START]      ;;					;AN000;
     MOV   [BP+DI+COLORPRINT_STR.SELECT_MASK],0 ;; Initialize band select mask		;AN000;
     POP   DI			       ;;					;AN000;
 .ENDIF 			       ;;					;AN000;
  XOR  DX,DX			       ;; For each band found "OR" the item     ;AN000;
 .REPEAT			       ;;  tag into the select mask		;AN000;
    MOV  CX,3			       ;; Avoid getting too many parms error	;AN000;
    CALL SysParse		       ;;  from parser				;AN000;
   .IF <AX EQ 0> ;;					;AN000;
     .IF <<[BUILD_STATE]> EQ YES> ;;					;AN000;
	  PUSH	DI		       ;;					;AN000;
	  MOV	DI,[BLOCK_START]      ;;					;AN000;
	  MOV	AL,[RESULT_TAG_grload3]      ;;					;AN000;
	  OR	[BP+DI+COLORPRINT_STR.SELECT_MASK],AL ;; OR the mask for this band into the	;AN000;
				       ;;  select mask for this color		;AN000;
	  POP	DI		       ;;					;AN000;
     .ENDIF			       ;;					;AN000;
   .ELSE			       ;;					;AN000;
      .IF <AX NE -1> ;;					;AN000;
	  OR   byte [STMT_ERROR],INVALID ;; parm is invalid			;AN000;
	  MOV  byte [PARSE_ERROR],YES ;;					;AN000;
	  MOV  byte [BUILD_STATE],NO ;;					;AN000;
      .ENDIF			       ;;					;AN000;
   .ENDIF			       ;;					;AN000;
 .UNTIL <AX EQ -1>, NEAR	;;					;AN000;
				       ;;					;AN000;
  RET				       ;;					;AN000;
				       ;;					;AN000;
